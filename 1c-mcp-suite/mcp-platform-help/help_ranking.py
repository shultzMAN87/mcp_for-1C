"""
Разнообразие выдачи поиска по справке платформы.

Зачем
─────
После HBK-1 в индексе стало 43 896 чанков вместо 41 062, и топ-5 стал
дефицитным ресурсом. Сразу вылезло то, что раньше сходило с рук: на запрос
«длина строки» две позиции из пяти занимал один объект —
`КвалификаторыСтроки.Длина` и `КвалификаторыСтроки.По умолчанию`, — а
`СтрДлина` оказывалась шестой. До HBK-1 тот же объект занимал позиции 1 и 3
из пяти, просто конкурентов было мало и это не мешало.

Что делаем
──────────
1. Один чанк на страницу. У страницы бывает несколько чанков (`card`,
   `description`, `syntax`), и попадание двух чанков одной страницы в
   выдачу — это буквально один и тот же ответ дважды. Лишние выбрасываем,
   оставляя лучший по скору.

2. Понижение повторов объекта. Второй результат одного объекта идёт с
   половиной своего скора, третий — с третью; дальше обычная сортировка
   по скору. Ничего не выбрасывается, сильный объект не голодает, но два
   соседних места одному объекту достаются только тогда, когда его второй
   результат честно сильнее чужого первого.

Две отвергнутые версии
──────────────────────
«Не более одного результата на объект» чинит `ph-002` в одну строку, но
`parent` у всех глобальных функций — «Глобальный контекст», и такое правило
схлопнуло бы `СтрДлина`, `СтрЗаменить`, `СтрНайти` в один результат на любом
запросе про строки.

Чередование по кругу (первая попытка, 14.08.2026) — по одному результату из
каждой группы, потом по второму. Выглядело безобиднее: ничего не
выбрасывается, меняется только порядок. На деле уронило `ph-003` («заменить
подстроку»): вся сильная выдача там принадлежит «Глобальному контексту», и
`СтрЗаменить` со скором 0.583 уехал во второй круг, пропустив вперёд чужие
результаты со скором 0.25. Перестановка, не смотрящая на скор, — слишком
грубый инструмент, а добор кандидатов втрое только усилил эффект: групп
стало больше, и первый круг забивался слабыми одиночками.

Модуль намеренно отделён от server.py и ничего не импортирует: чистые
функции над списком словарей проверяются тестами без Qdrant и без mcp.
"""

from __future__ import annotations

from typing import Any

Hit = dict[str, Any]


def page_key(hit: Hit) -> str:
    """
    Чем страница отличается от другой страницы.

    A-7. Здесь стоял один `file_path`, и комментарий рядом утверждал, что
    он уникален внутри .hbk. Утверждение верное — и недостаточное: после
    `HBK-1` контейнеров стало сорок, а путь внутри каждого свой. Индексатор
    насчитал 11 страниц из 27 тысяч под уже занятым путём.

    Цена этого именно здесь: `collapse_pages` считает такие страницы одной и
    выбрасывает вторую как дубль. Не отказ, не ошибка — просто выдача
    беднее на страницу, и заметить это со стороны нельзя.

    Ключ страницы — пара «контейнер + путь». `hbk_file` лежит в payload с
    самого начала (`hbk_chunker._common_fields`), брать его ниоткуда не
    нужно.
    """
    path = hit.get("file_path") or ""
    if path:
        book = hit.get("hbk_file") or ""
        return f"{book}|{path}" if book else path
    # Старая схема payload — без file_path. Падаем на имя, как и раньше.
    return (
        hit.get("full_name")
        or hit.get("name_ru")
        or hit.get("name_en")
        or ""
    )


def object_key(hit: Hit) -> str:
    """
    К какому объекту относится результат.

    Для методов и свойств это родитель (`Глобальный контекст`,
    `КвалификаторыСтроки`), для статей родителя нет — тогда каждая статья
    сама себе группа, иначе все статьи справки слиплись бы в одну.
    """
    parent = (hit.get("parent_ru") or hit.get("parent_en") or "").strip()
    if parent:
        return f"parent:{parent}"
    return f"page:{page_key(hit)}"


def collapse_pages(hits: list[Hit]) -> list[Hit]:
    """
    Оставляет по одному — лучшему — чанку на страницу.

    Порядок входа считается порядком убывания релевантности, поэтому
    «лучший» — это первый встреченный.
    """
    seen: set[str] = set()
    out: list[Hit] = []
    for hit in hits:
        key = page_key(hit)
        if key:
            if key in seen:
                continue
            seen.add(key)
        out.append(hit)
    return out


# Во сколько раз слабее учитывается n-й результат одного объекта: второй —
# вдвое, третий — втрое. Гармонический ряд, а не подобранный коэффициент:
# подбирать множитель по одному падающему примеру — прямой путь к подгонке.
def _repeat_penalty(occurrence: int) -> float:
    return 1.0 / occurrence


def demote_repeated_objects(hits: list[Hit]) -> list[Hit]:
    """
    Понижает повторные результаты одного объекта и пересортировывает.

    Ничего не удаляет. Сортировка стабильная: при равных значениях
    исходная очерёдность остаётся запасным критерием.
    """
    seen: dict[str, int] = {}
    weighted: list[tuple[float, int, Hit]] = []

    for position, hit in enumerate(hits):
        key = object_key(hit)
        occurrence = seen.get(key, 0) + 1
        seen[key] = occurrence
        try:
            score = float(hit.get("score") or 0.0)
        except (TypeError, ValueError):
            score = 0.0
        weighted.append((score * _repeat_penalty(occurrence), position, hit))

    weighted.sort(key=lambda row: (-row[0], row[1]))
    return [row[2] for row in weighted]


def diversify_hits(hits: list[Hit], limit: int) -> list[Hit]:
    """
    Полная обработка выдачи: дубли страниц убрать, повторы объекта
    понизить, обрезать до limit.
    """
    if not hits:
        return []
    return demote_repeated_objects(collapse_pages(hits))[:max(1, limit)]
