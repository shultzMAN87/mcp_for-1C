"""
SCALE-1 — работа в границах подсистемы.
========================================

Зачем. Конфигурация состоит из десятков подсистем (в боевой — 93), и
разработка почти всегда идёт внутри одной. Поиск по слову «заказ» по всей
базе даёт сотни совпадений, из которых к задаче относятся единицы. Граница
подсистемы — это и фильтр поиска, и способ удержать контекст агента.

Данные уже есть: подсистемы разбираются, рёбра `CONTAINS` построены,
вложенность — через `PARENT_OF`.

Три решения, каждое со своей причиной.

**Вложенность учитывается.** «Продажи» в 1С — это обычно верхний уровень с
десятком дочерних подсистем, и объекты висят на дочерних. Фильтр без обхода
вложенности вернул бы почти пустоту и выглядел бы как «в этой подсистеме
ничего нет» — худший вид неверного ответа.

**Имя принимается в любой форме.** Агент видит подсистему то как `Продажи`,
то как `Subsystem.Продажи`, то как `Подсистема.Продажи` — в зависимости от
того, какой инструмент её показал. Требовать угадывать форму значит
возвращать пустоту на верный запрос.

**Стейт держать негде.** Транспорт stateless (Streamable HTTP без сессий),
поэтому «текущая подсистема» не может быть состоянием сервера: соседний
запрос про него не узнает. Остаются два честных места — переменная
окружения уровня развёртывания и явный параметр вызова. Оба и сделаны:
`METADATA_DEFAULT_SUBSYSTEM` задаёт умолчание, параметр его перекрывает.
"""
from __future__ import annotations

import os

# Глубина обхода вложенных подсистем. Пять уровней — с запасом: в типовых
# конфигурациях вложенность редко больше трёх, а неограниченный обход на
# случайном цикле в данных крутился бы до таймаута.
SUBSYSTEM_MAX_DEPTH = 5

ENV_DEFAULT_SUBSYSTEM = "METADATA_DEFAULT_SUBSYSTEM"

# Значение, которым вызывающий явно отключает умолчание из окружения.
# Без него, задав METADATA_DEFAULT_SUBSYSTEM, нельзя было бы разово
# поискать по всей конфигурации — а это обычная нужда.
SCOPE_ALL = "*"


def resolve_subsystem(subsystem: str = "") -> str:
    """
    Какая подсистема действует для этого вызова.

    Приоритет: явный параметр → переменная окружения → пусто (вся база).
    `subsystem="*"` — явный отказ от умолчания, поиск по всей конфигурации.
    """
    explicit = (subsystem or "").strip()
    if explicit == SCOPE_ALL:
        return ""
    if explicit:
        return explicit
    return (os.environ.get(ENV_DEFAULT_SUBSYSTEM, "") or "").strip()


def normalize_subsystem_name(name: str) -> str:
    """
    Отрезает префикс вида `Subsystem.` / `Подсистема.`, если он есть.

    Имя самой подсистемы в графе лежит в `name` без префикса, а приходить
    может в любой форме — см. комментарий в шапке модуля.
    """
    raw = (name or "").strip()
    for prefix in ("subsystem.", "подсистема.", "подсистемы."):
        if raw.lower().startswith(prefix):
            return raw[len(prefix):]
    return raw


def subsystem_scope_cypher(alias: str = "n", param: str = "subsys") -> str:
    """
    Фрагмент Cypher: узел `alias` входит в заданную подсистему или любую
    из вложенных в неё.

    Возвращает выражение для WHERE — без самого слова WHERE, чтобы
    вызывающий сам решал, как склеить его с остальными условиями.

    `PARENT_OF*0..N` включает саму подсистему (ноль шагов), поэтому объекты,
    привязанные к корню, тоже попадают в выдачу.
    """
    return (
        f"EXISTS {{ MATCH (sub:MetadataObject {{kind_eng: 'Subsystem'}}) "
        f"WHERE (sub.name = ${param} OR sub.full_name_eng = ${param} "
        f"OR sub.full_name_ru = ${param}) "
        f"MATCH (sub)-[:PARENT_OF*0..{SUBSYSTEM_MAX_DEPTH}]->"
        f"(:MetadataObject)-[:CONTAINS]->({alias}) }}"
    )


def apply_scope(where_clauses: list[str], subsystem: str,
                alias: str = "n", param: str = "subsys") -> list[str]:
    """Добавляет условие подсистемы к списку клауз WHERE, если она задана."""
    if subsystem:
        return list(where_clauses) + [subsystem_scope_cypher(alias, param)]
    return list(where_clauses)


def scope_note(subsystem: str, total: int, found_any: bool) -> dict:
    """
    Поля ответа, объясняющие, что выдача ограничена.

    Ограниченная выдача без пометки — это тихая ложь: агент решит, что
    объектов больше нет, и пойдёт строить запрос по неполному списку. Тот
    же принцип, что в TOOL-2 и FIX-15.

    Отдельный случай — подсистема задана, а не нашлось ничего. Причин две:
    в подсистеме правда нет подходящих объектов либо имя подсистемы неверно.
    Различить их отсюда нельзя, поэтому честнее сказать про обе.
    """
    if not subsystem:
        return {}
    out = {
        "subsystem_scope": subsystem,
        "scope_note": (
            f"Выдача ограничена подсистемой «{subsystem}» и вложенными в неё. "
            f"Для поиска по всей конфигурации передайте subsystem=\"{SCOPE_ALL}\"."
        ),
    }
    if total == 0 and not found_any:
        out["scope_warning"] = (
            f"В подсистеме «{subsystem}» ничего не найдено. Либо там правда "
            f"нет таких объектов, либо имя подсистемы указано неверно — "
            f"список доступных даёт metadata_subsystems."
        )
    return out
